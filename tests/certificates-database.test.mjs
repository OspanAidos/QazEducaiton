import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const USER_PAID = "10000000-0000-4000-8000-000000000001";
const USER_UNPAID = "10000000-0000-4000-8000-000000000002";
const USER_WINNER = "10000000-0000-4000-8000-000000000003";
const APP_PAID = "20000000-0000-4000-8000-000000000001";
const APP_UNPAID = "20000000-0000-4000-8000-000000000002";
const APP_WINNER = "20000000-0000-4000-8000-000000000003";

const setupSql = `
  create role anon;
  create role authenticated;
  create role service_role;

  create schema auth;
  create schema storage;

  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable as
    $$ select null::uuid $$;

  create table storage.buckets (
    id text primary key,
    name text not null,
    public boolean not null default false,
    file_size_limit bigint
  );

  create table public.profiles (
    id uuid primary key references auth.users(id),
    first_name text,
    last_name text
  );

  create table public.applications (
    id uuid primary key,
    user_id uuid not null references auth.users(id),
    number text not null,
    status text not null,
    decision text,
    data jsonb not null default '{}'::jsonb,
    submitted_at timestamptz,
    result_published_at timestamptz,
    admin_status_comment text,
    admin_action_type text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
  );

  create table public.payments (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id),
    payment_type text not null,
    status text not null,
    amount_tenge numeric(12,2) not null,
    is_sandbox boolean not null default false,
    refunded_tenge numeric(12,2) not null default 0
  );

  create table public.competition_cycles (
    id integer primary key,
    updated_at timestamptz not null default now()
  );

  create table public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id),
    application_id uuid references public.applications(id),
    channel text not null,
    event_type text not null,
    payload jsonb not null default '{}'::jsonb,
    status text not null,
    error_text text
  );

  create function public.is_admin() returns boolean
  language sql stable as $$ select true $$;

  create function public.touch_updated_at() returns trigger
  language plpgsql as $$
  begin
    new.updated_at := now();
    return new;
  end;
  $$;

  create function public.qz_has_competition_access(p_user_id uuid)
  returns boolean language sql stable security definer set search_path = '' as $$
    select exists (
      select 1 from public.payments p
      where p.user_id = p_user_id
        and p.payment_type = 'competition_fee'
        and p.status = 'paid'
        and p.amount_tenge = 10000
        and not p.is_sandbox
        and p.refunded_tenge = 0
    )
  $$;

  insert into auth.users(id) values
    ('${USER_PAID}'), ('${USER_UNPAID}'), ('${USER_WINNER}');
  insert into public.profiles(id, first_name, last_name) values
    ('${USER_PAID}', 'Айдос', 'Оспан'),
    ('${USER_UNPAID}', 'Тест', 'Безоплаты'),
    ('${USER_WINNER}', 'Алия', 'Победитель');
  insert into public.competition_cycles(id) values (2026);
`;

async function database() {
  const db = new PGlite();
  await db.exec(setupSql);
  await db.exec(await readFile("../supabase/certificates-server-v2.sql", "utf8"));
  return db;
}

test("certificate migration runs and creates a private bucket", async () => {
  const db = await database();
  await db.exec(await readFile("../supabase/certificates-server-v2.sql", "utf8"));
  const result = await db.query(
    "select public, file_size_limit from storage.buckets where id = 'qazeducation-certificates-private'",
  );
  assert.deepEqual(result.rows, [{ public: false, file_size_limit: 15728640 }]);
  await db.close();
});

test("participant issuance requires real 10000 payment and remains idempotent", async () => {
  const db = await database();
  await db.exec(`
    insert into public.payments(user_id, payment_type, status, amount_tenge)
    values ('${USER_PAID}', 'competition_fee', 'paid', 10000);

    insert into public.applications(
      id, user_id, number, status, submitted_at, data
    ) values (
      '${APP_PAID}', '${USER_PAID}', 'QE-2026-000001', 'submitted',
      '2026-09-05T10:00:00+05:00', '{"support_type":"grant"}'::jsonb
    );

    insert into public.applications(
      id, user_id, number, status, submitted_at, data
    ) values (
      '${APP_UNPAID}', '${USER_UNPAID}', 'QE-2026-000002', 'submitted',
      '2026-09-05T10:05:00+05:00', '{"support_type":"grant"}'::jsonb
    );

    update public.applications set data = data || '{"city":"Astana"}'::jsonb
    where id = '${APP_PAID}';
  `);

  const certificates = await db.query(
    "select application_id, certificate_type, certificate_number from public.certificates order by application_id",
  );
  assert.equal(certificates.rows.length, 1);
  assert.equal(certificates.rows[0].application_id, APP_PAID);
  assert.equal(certificates.rows[0].certificate_type, "participant");
  assert.match(certificates.rows[0].certificate_number, /^QE-2026-P-000001$/);

  const notifications = await db.query(
    "select count(*)::integer as count from public.notifications where event_type = 'certificate_issued'",
  );
  assert.equal(notifications.rows[0].count, 1);
  await db.close();
});

test("published award is snapshotted and a changed decision revokes it", async () => {
  const db = await database();
  await db.exec(`
    update public.competition_cycles set
      certificate_basis_document = 'Протокол конкурсной комиссии',
      certificate_basis_number = '12/2026',
      certificate_basis_date = '2026-09-05'
    where id = 2026;

    insert into public.applications(
      id, user_id, number, status, decision, submitted_at,
      result_published_at, data
    ) values (
      '${APP_WINNER}', '${USER_WINNER}', 'QE-2026-000003', 'result',
      'scholarship', '2026-08-20T10:00:00+05:00',
      '2026-09-05T12:00:00+05:00',
      '{"support_type":"scholarship","university":"Академия права","specialty":"Юриспруденция"}'::jsonb
    );
  `);

  const issued = await db.query(
    "select id, verification_token, status, basis_text, metadata from public.certificates where application_id = $1 and certificate_type = 'scholarship'",
    [APP_WINNER],
  );
  assert.equal(issued.rows.length, 1);
  assert.equal(issued.rows[0].status, "active");
  assert.equal(
    issued.rows[0].basis_text,
    "Протокол конкурсной комиссии №12/2026 от 05.09.2026",
  );
  assert.equal(issued.rows[0].metadata.scholarship_amount_tenge, 50000);

  await db.exec(`
    update public.applications
    set decision = 'not_selected'
    where id = '${APP_WINNER}';
  `);

  const revoked = await db.query(
    "select status, revoked_at from public.certificates where id = $1",
    [issued.rows[0].id],
  );
  assert.equal(revoked.rows[0].status, "revoked");
  assert.ok(revoked.rows[0].revoked_at);

  const verified = await db.query(
    "select valid, certificate_status from public.verify_certificate($1)",
    [issued.rows[0].verification_token],
  );
  assert.deepEqual(verified.rows, [{ valid: false, certificate_status: "revoked" }]);
  await db.close();
});
